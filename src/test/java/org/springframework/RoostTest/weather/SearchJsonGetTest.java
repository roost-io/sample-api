		FieldConstraint itemsField = new FieldConstraint("object");
		Map<String, FieldConstraint> itemFields = new HashMap<>();

		itemFields.put("id", new FieldConstraint("integer").setFormat("int32"));
		itemFields.put("name", new FieldConstraint("string"));
		itemFields.put("region", new FieldConstraint("string"));
		itemFields.put("country", new FieldConstraint("string"));
		itemFields.put("lat", new FieldConstraint("number"));
		itemFields.put("lon", new FieldConstraint("number"));
		itemFields.put("url", new FieldConstraint("string"));

		itemsField.setNestedFields(itemFields);
		arrayField.setItemsConstraint(itemsField);

		schemasMap.put(200, schema200);

		ResponseSchema schema400 = new ResponseSchema();
		Map<String, FieldConstraint> fields400 = new HashMap<>();
		fields400.put("code", new FieldConstraint("integer").setFormat("int32"));
		fields400.put("message", new FieldConstraint("string"));
		schema400.setFields(fields400);
		schemasMap.put(400, schema400);

		ResponseSchema schema401 = new ResponseSchema();
		Map<String, FieldConstraint> fields401 = new HashMap<>();
		fields401.put("code", new FieldConstraint("integer").setFormat("int32"));
