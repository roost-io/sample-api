	private Response executeTest(Map<String, Object> testCase, Map<String, ParameterInfo> parameters,
			SecurityInfo security, String authValidityType) {
		Map<String, Object> queryParams = new HashMap<>();
		Map<String, Object> pathParams = new HashMap<>();
		Map<String, Object> headerParams = new HashMap<>();

		for (Map.Entry<String, Object> entry : testCase.entrySet()) {
			String key = entry.getKey();
			Object value = entry.getValue();

			if ("scenario".equals(key) || "expected_statusCode".equals(key) || "ScenarioID".equals(key)
					|| "TestName".equals(key) || "Description".equals(key) || "Execution".equals(key)
					|| "Validation".equals(key)) {
				continue;
			}

			if (value == null) {
				continue;
			}

			if ("headers".equals(key) && value instanceof Map) {
				Map<String, Object> headers = (Map<String, Object>) value;
				for (Map.Entry<String, Object> headerEntry : headers.entrySet()) {
					if (headerEntry.getValue() != null) {
						headerParams.put(headerEntry.getKey(), headerEntry.getValue());
					}
				}
				continue;
			}

			if ("query".equals(key) && value instanceof Map) {
				Map<String, Object> queries = (Map<String, Object>) value;
				for (Map.Entry<String, Object> queryEntry : queries.entrySet()) {
					if (queryEntry.getValue() != null) {
						queryParams.put(queryEntry.getKey(), queryEntry.getValue());
					}
				}
				continue;
			}

			if ("path".equals(key) && value instanceof Map) {
				Map<String, Object> paths = (Map<String, Object>) value;
				for (Map.Entry<String, Object> pathEntry : paths.entrySet()) {
					if (pathEntry.getValue() != null) {
						pathParams.put(pathEntry.getKey(), pathEntry.getValue());
					}
				}
				continue;
			}

			ParameterInfo paramInfo = parameters.get(key);
			if (paramInfo != null) {
				String location = paramInfo.getLocation();
				if ("query".equals(location)) {
					queryParams.put(key, value);
				}
				else if ("path".equals(location)) {
					pathParams.put(key, value);
				}
				else if ("header".equals(location)) {
					headerParams.put(key, value);
				}
			}
		}

		RequestSpecification request = given();

		if (security != null && security.getSchemeName() != null) {
			request = authHandler.applyAuth(request, security.getSchemeName(), authValidityType);
		}

		if (!queryParams.isEmpty()) {
			request.queryParams(queryParams);
		}
		if (!pathParams.isEmpty()) {
			request.pathParams(pathParams);
		}
		if (!headerParams.isEmpty()) {
			request.headers(headerParams);
		}

		logger.info("Executing {} request to {}", HTTP_METHOD.toUpperCase(), ENDPOINT);
		logger.debug("Query params: {}", queryParams);
		logger.debug("Path params: {}", pathParams);
		logger.debug("Header params: {}", headerParams);

		Response response;
		switch (HTTP_METHOD.toLowerCase()) {
			case "get":
				response = request.when().get(ENDPOINT);
				break;
			case "post":
				response = request.when().post(ENDPOINT);
				break;
			case "put":
				response = request.when().put(ENDPOINT);
				break;
			case "delete":
				response = request.when().delete(ENDPOINT);
				break;
			case "patch":
				response = request.when().patch(ENDPOINT);
				break;
			default:
				throw new IllegalArgumentException("Unsupported HTTP method: " + HTTP_METHOD);
		}

		logger.info("Response status code: {}", response.getStatusCode());
		return response;
	}

